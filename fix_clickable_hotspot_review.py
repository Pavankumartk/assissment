#!/usr/bin/env python3
"""Restore Clickable Hotspot's existing MCQ/Figma Review screen only.

Edits ONLY src/modules/assessments/components/common/AssessmentForm.tsx
and removes obsolete custom Review.tsx/review.css if and only if their SHA256
matches the copies generated by the previous ChatGPT integration.
No other assessment files or CSS are edited.
"""
import argparse
import hashlib
from pathlib import Path
import sys

parser=argparse.ArgumentParser()
parser.add_argument('web_root',nargs='?',default='.')
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
root=Path(args.web_root).resolve()
form=root/'src/modules/assessments/components/common/AssessmentForm.tsx'
if not form.is_file():sys.exit(f'STOP: Not found: {form}')
original=form.read_text(encoding='utf-8')
if 'import ReviewStep from "./steps/ReviewStep/ReviewStep";' not in original:
    sys.exit('STOP: The project does not match the supported shared ReviewStep flow. No files changed.')
if '"clickable-hotspot":' not in original:
    sys.exit('STOP: Clickable Hotspot integration not installed. Use the corrected FULL integration ZIP instead.')
s=original
# The original shared ReviewStep remains unchanged; only restore the routing to it.
s=s.replace('import ClickableHotspotReview from "../type-specific/clickable-hotspot/Review";\n','')
s=s.replace(' "clickable-hotspot": {details:DetailsStep, content:ClickableHotspotContent, evaluation:EvaluationStep, review:ClickableHotspotReview},',
            ' "clickable-hotspot": {details:DetailsStep, content:ClickableHotspotContent, evaluation:EvaluationStep, review:ReviewStep},')
s=s.replace('const Screen = step === "review" && typeCode !== "clickable-hotspot" ? ReviewStep : configured ? configured[step] : STEPS[step];',
            'const Screen = step === "review" ? ReviewStep : configured ? configured[step] : STEPS[step];')
if 'review:ClickableHotspotReview' in s or 'import ClickableHotspotReview ' in s:
    sys.exit('STOP: Unrecognized custom review reference. No files changed.')
if ' "clickable-hotspot": {details:DetailsStep, content:ClickableHotspotContent, evaluation:EvaluationStep, review:ReviewStep},' not in s:
    sys.exit('STOP: Clickable Hotspot assessment step mapping differs. No files changed.')
if 'const Screen = step === "review" ? ReviewStep : configured ? configured[step] : STEPS[step];' not in s:
    sys.exit('STOP: Review routing differs. No files changed.')
base=root/'src/modules/assessments/components/type-specific/clickable-hotspot'
known={
  'Review.tsx':'5d96ef2e806d25d51a46192c2b79de1557aa2fb2bb8d5df34ed12e431df46541',
  'review.css':'e551cdb1c120184348f54654c8523b7ac2b1199d23772564eacb2e53c040476e',
}
obsolete=[]
for name,h in known.items():
    file=base/name
    if file.exists():
        if hashlib.sha256(file.read_bytes()).hexdigest()==h:obsolete.append(file)
        else:print(f'Preserving modified file (unreferenced): {file.relative_to(root)}')
print(f'AssessmentForm needs correction: {s!=original}; old custom review files to remove: {len(obsolete)}')
for item in obsolete:print('  '+str(item.relative_to(root)))
if args.check:
    print('Dry run complete. No files changed.')
    sys.exit(0)
if s!=original:
    temporary=form.with_suffix('.tsx.hotspot-review-temp')
    try:
        temporary.write_text(s,encoding='utf-8')
        temporary.replace(form)
    finally:temporary.unlink(missing_ok=True)
for item in obsolete:item.unlink()
print('Fixed. Clickable Hotspot uses your existing shared ReviewStep. No other assessment flows changed.')
